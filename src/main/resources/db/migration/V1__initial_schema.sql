CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    phone_number VARCHAR(20),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE user_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id),
    task_reminders_enabled BOOLEAN NOT NULL,
    goal_milestone_updates_enabled BOOLEAN NOT NULL,
    habit_reminders_enabled BOOLEAN NOT NULL,
    ai_planner_updates_enabled BOOLEAN NOT NULL,
    time_zone_id VARCHAR(100) NOT NULL,
    date_format VARCHAR(20) NOT NULL,
    time_format VARCHAR(10) NOT NULL,
    week_start VARCHAR(10) NOT NULL,
    ai_response_style VARCHAR(20) NOT NULL,
    ai_personalization_enabled BOOLEAN NOT NULL
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expiry_date TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX idx_refresh_token_hash ON refresh_tokens (token_hash);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    color VARCHAR(7),
    user_id BIGINT NOT NULL,
    name_key VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_category_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_category_user_name UNIQUE (user_id, name_key)
);

CREATE INDEX idx_category_user ON categories (user_id);

CREATE TABLE goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    user_id BIGINT NOT NULL,
    goal_type VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    target_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    progress_percentage INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_goal_user_target ON goals (user_id, target_date);

CREATE TABLE goal_milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    goal_id BIGINT NOT NULL,
    target_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_milestone_goal FOREIGN KEY (goal_id) REFERENCES goals (id)
);

CREATE INDEX idx_milestone_goal_target ON goal_milestones (goal_id, target_date);

CREATE TABLE habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    user_id BIGINT NOT NULL,
    frequency VARCHAR(20) NOT NULL,
    target_days_per_week INTEGER NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_habit_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_habit_user_active ON habits (user_id, active);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    user_id BIGINT NOT NULL,
    category_id BIGINT,
    goal_id BIGINT,
    milestone_id BIGINT,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    status_before_completion VARCHAR(20),
    due_date TIMESTAMP WITHOUT TIME ZONE,
    start_date TIMESTAMP WITHOUT TIME ZONE,
    estimated_duration INTEGER,
    actual_duration INTEGER,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    missed_at TIMESTAMP WITHOUT TIME ZONE,
    recurring BOOLEAN NOT NULL,
    recurrence_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_task_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_task_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_task_goal FOREIGN KEY (goal_id) REFERENCES goals (id),
    CONSTRAINT fk_task_milestone FOREIGN KEY (milestone_id) REFERENCES goal_milestones (id),
    CONSTRAINT tasks_status_check CHECK (
        status IN ('TODO', 'IN_PROGRESS', 'COMPLETED', 'MISSED', 'CANCELLED')
    )
);

CREATE INDEX idx_task_user_created ON tasks (user_id, created_at);
CREATE INDEX idx_task_user_status ON tasks (user_id, status);
CREATE INDEX idx_task_user_due ON tasks (user_id, due_date);

CREATE TABLE habit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL,
    completion_date DATE NOT NULL,
    completed BOOLEAN NOT NULL,
    notes VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_habit_log_habit FOREIGN KEY (habit_id) REFERENCES habits (id),
    CONSTRAINT uk_habit_log_date UNIQUE (habit_id, completion_date)
);

CREATE TABLE notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    note_type VARCHAR(20) NOT NULL,
    pinned BOOLEAN NOT NULL,
    journal_date DATE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_note_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_note_user_journal_date UNIQUE (user_id, journal_date)
);

CREATE INDEX idx_note_user_updated ON notes (user_id, updated_at);
CREATE INDEX idx_note_user_type ON notes (user_id, note_type);

CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    reminder_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deadline_offset_minutes INTEGER,
    status VARCHAR(20) NOT NULL,
    reminder_type VARCHAR(30) NOT NULL,
    user_id BIGINT NOT NULL,
    task_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_reminder_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reminder_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE SET NULL
);

CREATE INDEX idx_reminder_user_date ON reminders (user_id, reminder_date_time);
CREATE INDEX idx_reminder_status_date ON reminders (status, reminder_date_time);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    notification_type VARCHAR(30) NOT NULL,
    event_key VARCHAR(200) UNIQUE,
    is_read BOOLEAN NOT NULL,
    user_id BIGINT NOT NULL,
    reminder_id BIGINT UNIQUE,
    task_id BIGINT,
    goal_id BIGINT,
    milestone_id BIGINT,
    habit_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_notification_reminder FOREIGN KEY (reminder_id) REFERENCES reminders (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_goal FOREIGN KEY (goal_id) REFERENCES goals (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_milestone FOREIGN KEY (milestone_id) REFERENCES goal_milestones (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_habit FOREIGN KEY (habit_id) REFERENCES habits (id) ON DELETE SET NULL,
    CONSTRAINT notifications_notification_type_check CHECK (
        notification_type IN (
            'REMINDER',
            'TASK_DEADLINE_APPROACHING',
            'TASK_OVERDUE',
            'TASK_COMPLETED',
            'TASK_MISSED',
            'TASK_RESCHEDULED',
            'MILESTONE_COMPLETED',
            'HABIT_COMPLETED',
            'AI_DAILY_PLAN_READY',
            'SYSTEM'
        )
    )
);

CREATE INDEX idx_notification_user_created ON notifications (user_id, created_at);

CREATE TABLE calendar_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    event_type VARCHAR(20) NOT NULL,
    all_day BOOLEAN NOT NULL,
    start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    recurrence_type VARCHAR(20) NOT NULL,
    user_id BIGINT NOT NULL,
    task_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_calendar_event_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_calendar_event_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE INDEX idx_calendar_user_start ON calendar_events (user_id, start_date_time);
CREATE INDEX idx_calendar_user_type ON calendar_events (user_id, event_type);

CREATE TABLE schedule_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    task_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_schedule_slot_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_schedule_slot_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE INDEX idx_schedule_user_start ON schedule_slots (user_id, start_date_time);
CREATE INDEX idx_schedule_user_end ON schedule_slots (user_id, end_date_time);
