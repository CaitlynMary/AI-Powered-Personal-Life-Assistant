import { ApplicationConfig, inject, provideAppInitializer, provideBrowserGlobalErrorListeners } from '@angular/core';
import { provideHttpClient, withInterceptors } from '@angular/common/http';
import { provideRouter } from '@angular/router';
import { authInterceptor } from './core/auth/auth.interceptor';
import { AuthService } from './core/auth/auth.service';
import { UserSettingsService } from './features/settings/data/user-settings.service';
import {
  provideLucideConfig,
  provideLucideIcons,
  LucideArrowRight,
  LucideBell,
  LucideBot,
  LucideCake,
  LucideCalendarClock,
  LucideCalendarDays,
  LucideCheck,
  LucideCheckSquare,
  LucideChevronDown,
  LucideCircleCheck,
  LucideCircleX,
  LucideClockAlert,
  LucideEye,
  LucideEyeOff,
  LucideFlame,
  LucideGraduationCap,
  LucideInbox,
  LucideLaptop,
  LucideLayers,
  LucideLayoutDashboard,
  LucideListChecks,
  LucideLoaderCircle,
  LucideLock,
  LucideLogOut,
  LucideMail,
  LucideMenu,
  LucideMessageCircle,
  LucideMoon,
  LucideNotebookPen,
  LucidePanelLeft,
  LucidePhone,
  LucidePlus,
  LucideRepeat,
  LucideSearch,
  LucideUser,
  LucideSettings,
  LucideSparkles,
  LucideSquareCheck,
  LucideStethoscope,
  LucideSun,
  LucideTarget,
  LucideZap,
} from '@lucide/angular';

import { routes } from './app.routes';

export const appConfig: ApplicationConfig = {
  providers: [
    provideBrowserGlobalErrorListeners(),
    provideRouter(routes),
    provideHttpClient(withInterceptors([authInterceptor])),
    provideAppInitializer(() => {
      const auth = inject(AuthService);
      const settings = inject(UserSettingsService);
      return auth.restoreSession().then(() => settings.loadForCurrentUser());
    }),
    provideLucideConfig({ size: 20, strokeWidth: 2 }),
    provideLucideIcons(
      LucideArrowRight,
      LucideBell,
      LucideBot,
      LucideCake,
      LucideCalendarClock,
      LucideCalendarDays,
      LucideCheck,
      LucideCheckSquare,
      LucideChevronDown,
      LucideCircleCheck,
      LucideCircleX,
      LucideClockAlert,
      LucideEye,
      LucideEyeOff,
      LucideFlame,
      LucideGraduationCap,
      LucideInbox,
      LucideLaptop,
      LucideLayers,
      LucideLayoutDashboard,
      LucideListChecks,
      LucideLoaderCircle,
      LucideLock,
      LucideLogOut,
      LucideMail,
      LucideMenu,
      LucideMessageCircle,
      LucideMoon,
      LucideNotebookPen,
      LucidePanelLeft,
      LucidePhone,
      LucidePlus,
      LucideRepeat,
      LucideSearch,
      LucideUser,
      LucideSettings,
      LucideSparkles,
      LucideSquareCheck,
      LucideStethoscope,
      LucideSun,
      LucideTarget,
      LucideZap,
    ),
  ],
};
